use crate::lockfile::LockedArtifact;
use crate::lockfile::LockedInput;
use crate::lockfile::LockedUpstream;
use miette::IntoDiagnostic;
use serde::Deserialize;
use serde::Serialize;
use std::path::Path;

/// File name of the lockfile next to `upstream.toml` in each vendored
/// crate.
pub const LOCKFILE_NAME: &str = "upstream.lock";

/// The `upstream.lock` lockfile: the resolved upstream commit plus the
/// SHA-256 of every vendored file, for drift detection and
/// reproducible verification.
#[derive(Debug, Default, Deserialize, Serialize)]
pub struct Lockfile {
    /// Resolved upstream coordinates.
    pub upstream: LockedUpstream,
    /// Every vendored file with its content hash, in manifest order.
    #[serde(default)]
    pub artifacts: Vec<LockedArtifact>,
    /// External non-git inputs fetched by providers (URLs + hashes).
    #[serde(default)]
    pub inputs: Vec<LockedInput>,
}

impl Lockfile {
    /// Reads the lockfile at `path`, returning `Ok(None)` when absent.
    pub fn load(path: &Path) -> miette::Result<Option<Self>> {
        match std::fs::read_to_string(path) {
            Ok(text) => toml::from_str(&text)
                .into_diagnostic()
                .map(Some)
                .map_err(|e| e.wrap_err(format!("Failed to parse {}", path.display()))),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(e).into_diagnostic().map_err(|e| e.wrap_err(format!("Failed to read {}", path.display()))),
        }
    }

    /// Writes the lockfile at `path` in a stable TOML layout.
    pub fn save(&self, path: &Path) -> miette::Result<()> {
        let body = toml::to_string_pretty(self)
            .into_diagnostic()
            .map_err(|e| e.wrap_err("Failed to serialize lockfile"))?;
        let header = "# Generated by `cargo xtask sync` - do not edit.\n# Run `cargo xtask verify -p <crate>` to check the vendored tree.\n\n";
        std::fs::write(path, format!("{header}{body}"))
            .into_diagnostic()
            .map_err(|e| e.wrap_err(format!("Failed to write {}", path.display())))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Round-trips a lockfile through TOML.
    #[test]
    fn lockfile_round_trip() {
        let lockfile = Lockfile {
            upstream: LockedUpstream {
                repo: "tailwindlabs/heroicons".to_string(),
                git_ref: "v2.2.0".to_string(),
                commit: "abc123".to_string(),
            },
            artifacts: vec![
                LockedArtifact {
                    target: "resources/LICENSE".to_string(),
                    sha256: "aa".to_string(),
                    source: "LICENSE".to_string(),
                },
                LockedArtifact {
                    target: "resources/metadata/aliases.json".to_string(),
                    sha256: "bb".to_string(),
                    source: "provider:iconify_aliases".to_string(),
                },
            ],
            inputs: vec![LockedInput {
                url: "https://unpkg.com/x".to_string(),
                sha256: "cc".to_string(),
                provider: "iconify_aliases".to_string(),
            }],
        };
        let text = toml::to_string_pretty(&lockfile).unwrap();
        let parsed: Lockfile = toml::from_str(&text).unwrap();
        assert_eq!(parsed.upstream.commit, "abc123");
        assert_eq!(parsed.artifacts.len(), 2);
        assert_eq!(parsed.artifacts[1].source, "provider:iconify_aliases");
        assert_eq!(parsed.inputs[0].provider, "iconify_aliases");
    }
}
