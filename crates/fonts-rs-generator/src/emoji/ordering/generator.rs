//! Codegen for emoji picker ordering data (`emoji_*_ordering.json`).
//!
//! [`EmojiOrderingGenerator`] takes a parsed [`EmojiOrdering`] plus a
//! family-provided sequence→glyph-name resolver and emits the static
//! tables the runtime ordering API needs:
//!
//! - `ordering.rs` - `ORDERING: phf::Map<&str, u32>` (base name → flat
//!   picker index over all ordered base entries)
//! - `groups.rs` - `GROUP_ORDER: &[GroupLabel]`, `GROUPS: &[GlyphGroup]`
//!   (ordered groups with resolved names, alternates inlined after
//!   their base) and `GROUP_OF: phf::Map<&str, &str>` (base and
//!   alternate names → group label)
//! - `alternates.rs` - `ALTERNATES: phf::Map<&str, &[&str]>` (base →
//!   variant names) and `BASE_OF: phf::Map<&str, &str>` (variant → base)
//! - `shortcodes.rs` - `SHORTCODES: phf::Map<&str, &[&str]>` (name →
//!   shortcodes + emoticons)
//! - `tone_groups.rs` - `TONE_GROUP: phf::Map<&str, u32>` (base name →
//!   opaque variant-shape group id; `0`/no tones is omitted)
//!
//! [`EmojiOrderingGenerator::run`] additionally returns the
//! shortcode/emoticon alias pairs so callers can feed them into a
//! [`MetadataGenerator`](crate::MetadataGenerator) alias map - search
//! hits `:smile:` without dedicated search code.
//!
//! Unresolvable sequences (upstream knows emoji the family does not
//! ship, or vice versa) are skipped: they get no ordering, group, or
//! alternate entries.

use std::path::PathBuf;

use fonts_rs_model::CodePoint;

use crate::emoji::ordering::EmojiOrdering;
use crate::escape_str;

/// Generates the emoji picker ordering tables.
///
/// The resolver closure joins a Unicode codepoint sequence onto the
/// family's exported glyph names - for blobmoji the same CLDR
/// sequence→name map `SvgDirSource` uses, then prefix + kebab +
/// membership check against the exported set.
pub struct EmojiOrderingGenerator<'a> {
    ordering: &'a EmojiOrdering,
}

impl<'a> EmojiOrderingGenerator<'a> {
    /// Creates a generator over a parsed ordering document.
    pub fn new(ordering: &'a EmojiOrdering) -> Self {
        Self { ordering }
    }

    /// Emits `ordering.rs`, `groups.rs`, `alternates.rs`,
    /// `shortcodes.rs`, and `tone_groups.rs` into `OUT_DIR`.
    ///
    /// Returns the `(alias, canonical_name)` pairs collected from
    /// shortcodes and emoticons - pass them to
    /// [`EmojiMetadataGenerator::with_aliases`](crate::emoji::EmojiMetadataGenerator::with_aliases)
    /// (or another `MetadataGenerator`) so `resolve_alias`/`search` see them.
    ///
    /// # Errors
    ///
    /// Returns an I/O error when `OUT_DIR` is unset or a file cannot be
    /// written.
    pub fn run(&self, resolve: impl Fn(&[CodePoint]) -> Option<String>) -> Result<Vec<(String, String)>, std::io::Error> {
        let out_dir = std::env::var("OUT_DIR").map_err(|e| std::io::Error::other(format!("OUT_DIR not set: {e}")))?;
        let out_dir = PathBuf::from(out_dir);
        std::fs::create_dir_all(&out_dir)?;

        // Resolve every sequence once: (flat base index, resolved names).
        let mut position: u32 = 0;
        let mut ordering_src = String::from("// @generated by build.rs - do not edit\n\npub static ORDERING: phf::Map<&'static str, u32> = phf::phf_map! {\n");
        let mut groups_src = String::from("// @generated by build.rs - do not edit\n\npub static GROUP_ORDER: &[GroupLabel] = &[\n");
        let mut group_of_src = String::from("\npub static GROUP_OF: phf::Map<&'static str, &'static str> = phf::phf_map! {\n");
        let mut groups_slice_src = String::from("\npub static GROUPS: &[GlyphGroup] = &[\n");
        let mut alternates_src = String::from(
            "// @generated by build.rs - do not edit\n\npub static ALTERNATES: phf::Map<&'static str, &'static [&'static str]> = phf::phf_map! {\n",
        );
        let mut base_of_src = String::from("\npub static BASE_OF: phf::Map<&'static str, &'static str> = phf::phf_map! {\n");
        let mut shortcodes_src = String::from(
            "// @generated by build.rs - do not edit\n\npub static SHORTCODES: phf::Map<&'static str, &'static [&'static str]> = phf::phf_map! {\n",
        );
        let mut tone_groups_src =
            String::from("// @generated by build.rs - do not edit\n\npub static TONE_GROUP: phf::Map<&'static str, u32> = phf::phf_map! {\n");
        let mut aliases: Vec<(String, String)> = Vec::new();
        let mut seen_aliases: std::collections::HashSet<&str> = std::collections::HashSet::new();
        // Distinct upstream sequences can resolve to the same glyph name
        // (e.g. U+2603/U+26C4 both map to the CLDR name "snowman") -
        // emit each glyph name once, first occurrence in picker order wins.
        let mut emitted: std::collections::HashSet<String> = std::collections::HashSet::new();
        let mut misses: usize = 0;

        for group in &self.ordering.0 {
            groups_src.push_str(&format!("    GroupLabel::new(\"{}\"),\n", escape_str(&group.group)));
            let mut group_names: Vec<String> = Vec::new();
            for emoji in &group.emoji {
                let base_sequence: Vec<CodePoint> = emoji.base.iter().filter_map(|v| char::from_u32(*v)).map(CodePoint::from).collect();
                let Some(base_name) = resolve(&base_sequence) else {
                    misses += 1;
                    continue;
                };
                if !emitted.insert(base_name.clone()) {
                    continue;
                }

                ordering_src.push_str(&format!("    \"{}\" => {}u32,\n", escape_str(&base_name), position));
                position += 1;
                group_of_src.push_str(&format!("    \"{}\" => \"{}\",\n", escape_str(&base_name), escape_str(&group.group)));
                // Tone group: opaque shape key for default-tone picking;
                // 0 means "no tone variants" and stays absent so
                // `tone_group` can return `None` for plain glyphs.
                if emoji.tone_group != 0 {
                    tone_groups_src.push_str(&format!("    \"{}\" => {}u32,\n", escape_str(&base_name), emoji.tone_group));
                }

                // Variant names: alternates[1..] (alternates[0] is the base
                // itself in upstream data; the emitted set already filters
                // it together with any other duplicate resolution).
                let mut variant_names: Vec<String> = Vec::new();
                for alternate in &emoji.alternates {
                    let sequence: Vec<CodePoint> = alternate.iter().filter_map(|v| char::from_u32(*v)).map(CodePoint::from).collect();
                    let Some(name) = resolve(&sequence) else { continue };
                    if !emitted.insert(name.clone()) {
                        continue;
                    }
                    group_of_src.push_str(&format!("    \"{}\" => \"{}\",\n", escape_str(&name), escape_str(&group.group)));
                    base_of_src.push_str(&format!("    \"{}\" => \"{}\",\n", escape_str(&name), escape_str(&base_name)));
                    variant_names.push(name);
                }

                group_names.push(base_name.clone());
                group_names.extend(variant_names.iter().cloned());

                if !variant_names.is_empty() {
                    let refs: Vec<String> = variant_names.iter().map(|name| format!("\"{}\"", escape_str(name))).collect();
                    alternates_src.push_str(&format!("    \"{}\" => &[{}],\n", escape_str(&base_name), refs.join(", ")));
                }

                let mut search_terms: Vec<&str> = emoji.shortcodes.iter().chain(emoji.emoticons.iter()).map(String::as_str).collect();
                if !search_terms.is_empty() {
                    search_terms.sort_unstable();
                    search_terms.dedup();
                    let refs: Vec<String> = search_terms.iter().map(|term| format!("\"{}\"", escape_str(term))).collect();
                    shortcodes_src.push_str(&format!("    \"{}\" => &[{}],\n", escape_str(&base_name), refs.join(", ")));
                    for term in &search_terms {
                        // The same shortcode can map to several emoji
                        // (e.g. ':snowman-with-snow:') - first base in
                        // picker order wins the alias.
                        if seen_aliases.insert(*term) {
                            aliases.push(((*term).to_string(), base_name.clone()));
                        }
                    }
                }
            }
            if !group_names.is_empty() {
                let refs: Vec<String> = group_names.iter().map(|name| format!("\"{}\"", escape_str(name))).collect();
                groups_slice_src.push_str(&format!("    GlyphGroup::new(GroupLabel::new(\"{}\"), &[{}]),\n", escape_str(&group.group), refs.join(", ")));
            }
        }

        groups_src.push_str("];\n");
        groups_src.push_str(&group_of_src);
        groups_src.push_str("};\n");
        groups_src.push_str(&groups_slice_src);
        groups_src.push_str("];\n");

        ordering_src.push_str("};\n");
        alternates_src.push_str("};\n");
        alternates_src.push_str(&base_of_src);
        alternates_src.push_str("};\n");
        shortcodes_src.push_str("};\n");
        tone_groups_src.push_str("};\n");

        std::fs::write(out_dir.join("ordering.rs"), ordering_src)?;
        std::fs::write(out_dir.join("groups.rs"), groups_src)?;
        std::fs::write(out_dir.join("alternates.rs"), alternates_src)?;
        std::fs::write(out_dir.join("shortcodes.rs"), shortcodes_src)?;
        std::fs::write(out_dir.join("tone_groups.rs"), tone_groups_src)?;

        if misses > 0 {
            eprintln!("ordering generator: {misses} unresolved base sequences skipped");
        }
        Ok(aliases)
    }
}
