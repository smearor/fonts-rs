//! The [`IconSetModuleGenerator`] - emits `iconset.rs` into `OUT_DIR`.

use crate::generator::error::GenerateError;
use crate::generator::metadata_generator::escape_str;
use fonts_rs_model::IconSetSpec;
use std::fs;
use std::path::PathBuf;

/// Generates `iconset.rs` - the complete, self-contained module an
/// application includes with one line:
///
/// ```ignore
/// include!(concat!(env!("OUT_DIR"), "/iconset.rs"));
/// ```
///
/// The generated module contains the marker type, `sealed::Sealed` /
/// `FontFamilyMarker` impls, a `FontFamilyConfig` impl built from the
/// spec values, the `impl_font_family!`/`impl_gtk_font!` invocations,
/// and the `codemap`/`icon_names` module includes.
pub struct IconSetModuleGenerator;

impl IconSetModuleGenerator {
    /// Writes `iconset.rs` into `OUT_DIR`.
    ///
    /// # Errors
    ///
    /// Returns [`GenerateError`] when `OUT_DIR` is unset or the write
    /// fails.
    pub fn run(spec: &IconSetSpec) -> Result<(), GenerateError> {
        let out_dir = std::env::var("OUT_DIR")?;
        fs::write(PathBuf::from(out_dir).join("iconset.rs"), Self::generate(spec))?;
        Ok(())
    }

    /// The name alias type: `{Name}IconName`, stripping a trailing
    /// `Icons` plural so `MyAppIcons` produces `MyAppIconName`.
    fn name_alias(marker_name: &str) -> String {
        let base = marker_name.strip_suffix("Icons").unwrap_or(marker_name);
        format!("{base}IconName")
    }

    /// Generates the module source for the spec.
    ///
    /// `display_name` is free text and is string-escaped; the remaining
    /// values are validation-gated formats (PascalCase marker, kebab
    /// prefix, `/…` path).
    pub fn generate(spec: &IconSetSpec) -> String {
        let name = &spec.name;
        let alias = Self::name_alias(name);
        let display_name = escape_str(&spec.display_name);
        format!(
            "// @generated by fonts-rs-generator IconSetBuild - do not edit\n\
             // Regenerate via `IconSetBuild::from_file(\"icons.toml\")` in build.rs.\n\n\
             /// Build-time configuration for the `{icon_prefix}` custom icon set.\n\
             pub struct {name}Config;\n\n\
             impl ::fonts_rs_model::FontFamilyConfig for {name}Config {{\n\
             \x20   /// Cargo feature / icon set identifier.\n\
             \x20   const FONT_FAMILY_NAME: &'static str = \"{icon_prefix}\";\n\
             \x20   /// Human-readable display name.\n\
             \x20   const FAMILY_DISPLAY_NAME: &'static str = \"{display_name_escaped}\";\n\
             \x20   /// GResource path prefix for this icon set's resources.\n\
             \x20   const GRESOURCE_PREFIX: &'static str = \"{gresource_prefix}\";\n\
             \x20   /// Freedesktop icon context for the exported glyphs.\n\
             \x20   const ICONS_CONTEXT: &'static str = \"{icons_context}\";\n\
             \x20   /// Prefix for icon names and CSS classes.\n\
             \x20   const ICON_PREFIX: &'static str = \"{icon_prefix}-\";\n\
             }}\n\n\
             /// Marker type identifying the `{display_name}` icon set in\n\
             /// `GlyphName<{name}>`.\n\
             #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]\n\
             pub enum {name} {{}}\n\n\
             impl ::fonts_rs_model::sealed::Sealed for {name} {{}}\n\
             impl ::fonts_rs_model::FontFamilyMarker for {name} {{}}\n\n\
             /// Typed glyph name for {display_name} icons.\n\
             pub type {alias} = ::fonts_rs_model::GlyphName<{name}>;\n\n\
             mod codepoint_map {{\n\
             \x20   include!(concat!(env!(\"OUT_DIR\"), \"/codemap.rs\"));\n\
             }}\n\n\
             /// Icon name constants for `Image::from_icon_name`.\n\
             pub mod icon_names {{\n\
             \x20   include!(concat!(env!(\"OUT_DIR\"), \"/icons.rs\"));\n\
             }}\n\n\
             ::fonts_rs_generator::impl_font_family!(\n\
             \x20   {name},\n\
             \x20   {name}Config,\n\
             \x20   glyphs = codepoint_map::GLYPHS,\n\
             \x20   reverse = codepoint_map::REVERSE_GLYPHS,\n\
             \x20   name = {alias},\n\
             \x20   glyph_prefix = \"{icon_prefix}\",\n\
             \x20   capabilities = [icon_theme, html_svg],\n\
             );\n\n\
             #[cfg(feature = \"gtk\")]\n\
             ::fonts_rs_generator::impl_gtk_font!({name});\n",
            icon_prefix = spec.icon_prefix,
            display_name = spec.display_name,
            display_name_escaped = display_name,
            gresource_prefix = spec.gresource_prefix,
            icons_context = spec.icons_context,
        )
    }
}
