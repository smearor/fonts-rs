//! The [`ProjectExport`] - a compile-ready scaffold crate emitted as
//! a zip archive.

use crate::builder_settings::BuilderSettings;
use crate::icon_selection::IconSelection;
use crate::icon_selection::IconSelectionError;
use std::io::Write;

/// Packages the emitted `icons.toml` with the consumer-side plumbing
/// (`Cargo.toml`, `build.rs`, `src/lib.rs`) into a zip whose contents
/// `cargo build`s out of the box - the shape `fonts-rs-iconset-test`
/// exercises.
pub struct ProjectExport;

/// One file inside the exported project tree.
struct ExportFile {
    /// Path relative to the project root (`src/lib.rs`).
    path: String,
    /// File contents (UTF-8).
    content: String,
}

impl ProjectExport {
    /// PascalCase set name → kebab-case package name (`AppIcons` →
    /// `app-icons`).
    pub fn package_name(set_name: &str) -> String {
        let mut kebab = String::new();
        for ch in set_name.chars() {
            if ch.is_ascii_uppercase() && !kebab.is_empty() {
                kebab.push('-');
            }
            kebab.push(ch.to_ascii_lowercase());
        }
        kebab
    }

    /// Writes a `{prefix}-icons.zip` project scaffold to `path`.
    /// Returns the emitted `icons.toml` text (useful for toasts/logs).
    pub fn write_zip(selection: &IconSelection, settings: &BuilderSettings, path: &std::path::Path) -> Result<(), ProjectExportError> {
        let file = std::fs::File::create(path)?;
        let mut zip = zip::ZipWriter::new(file);
        let options: zip::write::FileOptions<'static, ()> = zip::write::FileOptions::default();
        for export in Self::files(selection, settings)? {
            zip.start_file(&export.path, options)?;
            zip.write_all(export.content.as_bytes())?;
        }
        zip.finish()?;
        Ok(())
    }

    /// All project files, in write order.
    fn files(selection: &IconSelection, settings: &BuilderSettings) -> Result<Vec<ExportFile>, IconSelectionError> {
        let package = Self::package_name(&settings.name);
        Ok(vec![
            ExportFile { path: "Cargo.toml".to_string(), content: cargo_toml(selection, &package) },
            ExportFile { path: "icons.toml".to_string(), content: selection.to_toml(settings)? },
            ExportFile { path: "build.rs".to_string(), content: build_rs().to_string() },
            ExportFile { path: "src/lib.rs".to_string(), content: lib_rs(&settings.name) },
        ])
    }
}

/// `[build-dependencies]` gets the generator; `[dependencies]` the
/// model plus the actually-picked source crates (their `links`
/// metadata feeds `DEP_*_SVG_DIR` into `build.rs`).
fn cargo_toml(selection: &IconSelection, package: &str) -> String {
    let mut deps = String::from("fonts-rs-model = \"0.5\"\n");
    let mut crates: Vec<&'static str> = selection.groups().map(|(_key, source, _icons)| source.crate_name).collect();
    crates.sort_unstable();
    crates.dedup();
    for crate_name in crates {
        deps.push_str(&format!("{crate_name} = \"0.5\"\n"));
    }
    format!(
        "[package]\n\
         name = \"{package}\"\n\
         version = \"0.1.0\"\n\
         edition = \"2024\"\n\
         description = \"Custom icon set exported by fonts-rs-iconset-builder\"\n\
         \n\
         [build-dependencies]\n\
         fonts-rs-generator = \"0.5\"\n\
         miette = \"7.6\"\n\
         \n\
         [dependencies]\n\
         {deps}",
        package = package,
        deps = deps,
    )
}

/// One-liner build script - exactly the CUSTOM_ICON_SET surface.
fn build_rs() -> &'static str {
    "fn main() -> miette::Result<()> {\n\
     \x20   fonts_rs_generator::IconSetBuild::from_file(\"icons.toml\")?.run()?;\n\
     \x20   Ok(())\n\
     }\n"
}

/// The generated module include + re-export; `pub use icons::*` keeps
/// it correct whatever marker/name types `icons.toml` generates.
fn lib_rs(set_name: &str) -> String {
    format!(
        "//! Custom icon set `{set_name}` - generated by `IconSetBuild`.\n\
         \n\
         pub mod icons {{\n\
         \x20   include!(concat!(env!(\"OUT_DIR\"), \"/iconset.rs\"));\n\
         }}\n\
         \n\
         pub use icons::*;\n"
    )
}

/// Errors when writing a project export.
#[derive(Debug, thiserror::Error)]
pub enum ProjectExportError {
    /// Spec assembly/serialization failed.
    #[error(transparent)]
    Spec(#[from] IconSelectionError),
    /// File I/O failed.
    #[error(transparent)]
    Io(#[from] std::io::Error),
    /// Zip writer failed.
    #[error(transparent)]
    Zip(#[from] zip::result::ZipError),
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::builder_settings::BuilderSettings;

    fn settings() -> BuilderSettings {
        BuilderSettings {
            name: "AppIcons".to_string(),
            display_name: "App Icons".to_string(),
            icon_prefix: "app".to_string(),
            gresource_prefix: "/com/example/app/icons".to_string(),
            icons_context: "actions".to_string(),
        }
    }

    #[test]
    fn package_name_kebabs_pascal() {
        assert_eq!(ProjectExport::package_name("AppIcons"), "app-icons");
        assert_eq!(ProjectExport::package_name("Fixture"), "fixture");
    }

    #[test]
    fn files_cover_the_compile_surface() {
        let mut selection = IconSelection::new();
        selection.add("lucide-check-symbolic");
        let files = ProjectExport::files(&selection, &settings()).unwrap();
        let paths: Vec<&str> = files.iter().map(|file| file.path.as_str()).collect();
        assert_eq!(paths, ["Cargo.toml", "icons.toml", "build.rs", "src/lib.rs"]);

        let cargo = files.iter().find(|file| file.path == "Cargo.toml").unwrap();
        assert!(cargo.content.contains("name = \"app-icons\""));
        assert!(cargo.content.contains("fonts-rs-lucide = \"0.5\""));
        assert!(cargo.content.contains("[build-dependencies]"));

        let lib = files.iter().find(|file| file.path == "src/lib.rs").unwrap();
        assert!(lib.content.contains("include!(concat!(env!(\"OUT_DIR\")"));
    }

    #[test]
    fn write_zip_produces_readable_archive() {
        let mut selection = IconSelection::new();
        selection.add("lucide-check-symbolic");
        let path = std::env::temp_dir().join(format!("export-test-{}.zip", std::process::id()));
        ProjectExport::write_zip(&selection, &settings(), &path).unwrap();
        let mut archive = zip::ZipArchive::new(std::fs::File::open(&path).unwrap()).unwrap();
        assert_eq!(archive.len(), 4);
        let mut names: Vec<String> = (0..archive.len()).filter_map(|i| archive.by_index(i).ok().map(|f| f.name().to_string())).collect();
        names.sort();
        assert_eq!(names, ["Cargo.toml", "build.rs", "icons.toml", "src/lib.rs"]);
        let _ = std::fs::remove_file(&path);
    }
}
